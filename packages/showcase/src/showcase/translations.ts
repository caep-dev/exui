export function translate(language: ShowcaseLanguage, english: string): string {
  if (language !== "zh-CN") return english
  const message = english.trim()
  const translated = chinese[message]
  if (!translated) return english
  return english.slice(0, english.indexOf(message)) + translated + english.slice(english.indexOf(message) + message.length)
}

export function useT() {
  const { language } = useShowcaseLanguage()
  return (english: string) => translate(language, english)
}

export function useIssueSeparator() {
  return useShowcaseLanguage().language === "zh-CN" ? "；" : "; "
}
